fun normalizeAppLanguageCode(code: String?): String {
    val normalized = code
        ?.trim()
        ?.lowercase()
        ?.substringBefore('-')
        ?.ifBlank { null }

    return when (normalized) {
        "en", "ja", "zh", "ko", "ru" -> normalized
        else -> "ru"
    }
}

fun appStringsForCode(code: String): AppStrings = when (normalizeAppLanguageCode(code)) {
    "en" -> English
    "ja" -> Japanese
    "zh" -> ChineseSimplified
    "ko" -> Korean
    else -> Russian
}

