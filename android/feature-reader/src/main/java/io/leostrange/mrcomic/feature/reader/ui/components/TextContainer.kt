    onExplainSelection: (String) -> Unit,
    onSaveQuoteSelection: (String) -> Unit,
    onHighlightSelection: (ReaderTextSelection) -> Unit = {},
    onTranslateChapter: () -> Unit = {},
    onCompareTranslations: (String) -> Unit = {},
