    overrideBackgroundColor: String? = null,
    overrideAccentColor: String? = null,
    translateActionLabel: String,
    dictionaryActionLabel: String,
    explainActionLabel: String,
    saveQuoteActionLabel: String,
    selectionMenuLanguageCode: String = "en",
    onRegisterPageTurner: ((Int) -> Unit) -> Unit = {},
    onSelectionActionModeChange: (Boolean) -> Unit = {},
    modifier: Modifier = Modifier
) {
    HtmlPageView(
        html = html,
        baseUrl = baseUrl,
        assetDocumentPath = assetDocumentPath,
        documentIdentity = documentIdentity,
        assetLoader = assetLoader,
        onLeftTap = onLeftTap,
        onRightTap = onRightTap,
        onCenterTap = onCenterTap,
        onTranslateSelection = onTranslateSelection,
        onDictionarySelection = onDictionarySelection,
        onExplainSelection = onExplainSelection,
        onSaveQuoteSelection = onSaveQuoteSelection,
        onHighlightSelection = onHighlightSelection,
        onTranslateChapter = onTranslateChapter,
        onCompareTranslations = onCompareTranslations,
        highlightsJs = highlightsJs,
        onAnchorClick = onAnchorClick,
        onInlineFootnote = onInlineFootnote,
        onVerticalBoundaryNavigation = onVerticalBoundaryNavigation,
        onPagedLayoutPageCountChanged = onPagedLayoutPageCountChanged,
        sectionCharacterOffset = sectionCharacterOffset,
        pendingScrollToAnchor = pendingScrollToAnchor,
        onConsumeScrollToAnchor = onConsumeScrollToAnchor,
        pendingWebtoonSectionIndex = pendingWebtoonSectionIndex,
        onConsumeWebtoonSection = onConsumeWebtoonSection,
